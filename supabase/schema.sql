  if p_payment_failed and p_payment_status <> 'unpaid' then raise exception 'failed payment must be unpaid'; end if;
  if v_paid and p_payment_confirmed_at is null then raise exception 'paid Stripe order requires a payment confirmation time'; end if;
  if not v_paid and p_payment_confirmed_at is not null then raise exception 'unpaid Stripe order cannot have a payment confirmation time'; end if;
  if p_travel_start is null or p_travel_end is null or p_travel_end < p_travel_start then raise exception 'invalid Pocket WiFi travel dates'; end if;
  if p_amount_sgd is null or p_amount_sgd <= 0 then raise exception 'invalid Pocket WiFi payment amount'; end if;

  perform pg_advisory_xact_lock(hashtext('qy_roam_pocket_wifi_checkout'));
  select * into v_order from public.orders where stripe_session_id = p_stripe_session_id for update;

  -- Offline sales use a deterministic, hashed internal id derived from the
  -- operator's payment/sales reference. Treat a retry of the same sale as an
  -- idempotent read, never as permission to rewrite a paid rental or reserve
  -- a second overlapping router. Different details under one reference need
  -- explicit operational reconciliation instead of an implicit overwrite.
  if found and p_stripe_session_id like 'manual_%' then
    if v_order.payment_status is distinct from p_payment_status
      or v_order.customer_name is distinct from p_customer_name
      or v_order.email is distinct from p_email
      or v_order.phone is distinct from p_phone
      or v_order.amount_sgd is distinct from p_amount_sgd
      or v_order.plan_name is distinct from p_plan_name
      or v_order.country is distinct from p_country
      or v_order.travel_start is distinct from p_travel_start
      or v_order.travel_end is distinct from p_travel_end then
      raise exception 'manual order reference already belongs to different order details';
    end if;
    return v_order;
  end if;

  -- An out-of-order failed event must never downgrade an already-paid order.
  if found and v_order.payment_status = 'paid' and not v_paid then
    delete from public.checkout_reservations
    where checkout_request_id = p_checkout_request_id and stripe_session_id = p_stripe_session_id;
    return v_order;
  end if;

  -- `payment_failed` is a terminal Checkout outcome. The only supported
  -- delayed-payment promotion is awaiting_payment -> paid. Reopening a failed
  -- Pocket WiFi row here would be especially dangerous: the failed terminal
  -- event releases its short-lived reservation, so another traveller may
  -- already hold the same rental dates. Keep this check in the privileged
  -- RPC as well as the application persistence path so a future worker cannot
  -- bypass the inventory boundary.
  if found and v_paid and v_order.fulfilment_status = 'payment_failed' then
    raise exception 'paid Stripe event cannot reopen a terminally failed order';
  end if;

  v_fulfilment := case
    when v_paid and found and v_order.fulfilment_status not in ('awaiting_payment','payment_failed') then v_order.fulfilment_status
    when v_paid then 'paid'
    when p_payment_failed and found and v_order.fulfilment_status not in ('awaiting_payment','payment_failed') then v_order.fulfilment_status
    when p_payment_failed then 'payment_failed'
    when found then v_order.fulfilment_status
    else 'awaiting_payment'
  end;

  insert into public.orders (
    stripe_session_id,payment_status,customer_name,email,phone,amount_sgd,
    product_type,plan_name,country,travel_start,travel_end,fulfilment_status,
    payment_confirmed_at,measurement_consent,shipping_address,updated_at
  ) values (
    p_stripe_session_id,p_payment_status,p_customer_name,p_email,p_phone,p_amount_sgd,
    'pocket_wifi',p_plan_name,p_country,p_travel_start,p_travel_end,v_fulfilment,
    case when v_paid then p_payment_confirmed_at else null end,p_measurement_consent,p_shipping_address,now()
  )
  on conflict (stripe_session_id) do update set
    payment_status = excluded.payment_status,
    customer_name = excluded.customer_name,
    email = excluded.email,
    phone = excluded.phone,
    amount_sgd = excluded.amount_sgd,
    plan_name = excluded.plan_name,
    country = excluded.country,
    travel_start = excluded.travel_start,
    travel_end = excluded.travel_end,
    fulfilment_status = v_fulfilment,
    payment_confirmed_at = case when v_paid then coalesce(orders.payment_confirmed_at, p_payment_confirmed_at) else orders.payment_confirmed_at end,
    measurement_consent = excluded.measurement_consent,
    shipping_address = excluded.shipping_address,
    updated_at = now()
  returning * into v_order;

  -- The durable order now represents the commitment, including while an
  -- asynchronous payment is pending, so retaining the hold would double-count.
  delete from public.checkout_reservations
  where checkout_request_id = p_checkout_request_id and stripe_session_id = p_stripe_session_id;
  return v_order;
end;
$$;
