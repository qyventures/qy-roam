-- The physical hand-off and receipt boundaries must update an order and its
-- stock ledger in one transaction. A browser-side sequence of "set status",
-- then "adjust stock" can otherwise leave a dispatched router available (or a
-- returned router missing) if either request is interrupted.
-- Replace the previous seven-argument routine rather than overloading it.
-- PostgREST resolves RPCs by named arguments, and retaining both versions
-- could let an older caller bypass the return-disposition boundary.
drop function if exists public.qy_transition_pocket_wifi_order(bigint,text,text,text,text,text,bigint);
create or replace function public.qy_transition_pocket_wifi_order(
  p_order_id bigint,
  p_expected_status text,
  p_next_status text,
  p_courier_tracking text,
  p_return_tracking text,
  p_notes text,
  p_inventory_item_id bigint,
  -- Returning a device can restore public capacity. Require an explicit
  -- inspection decision from every caller rather than defaulting an omitted
  -- field to restock.
  p_return_disposition text
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item public.inventory_items%rowtype;
  v_now timestamptz := now();
  v_item_id bigint;
  v_return_disposition text;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'order not found'; end if;
  if v_order.product_type <> 'pocket_wifi' or v_order.payment_status <> 'paid' then
    raise exception 'only paid Pocket WiFi orders can be transitioned here';
  end if;
  if v_order.fulfilment_status <> p_expected_status then
    raise exception 'order changed since it was loaded';
  end if;

  if not (
    p_next_status = p_expected_status or
    (p_expected_status = 'paid' and p_next_status in ('packing', 'dispatched', 'cancelled')) or
    (p_expected_status = 'packing' and p_next_status in ('paid', 'dispatched', 'cancelled')) or
    -- Dispatch is a physical, audited boundary. A router cannot move back to
    -- packing or be cancelled after hand-off; it must remain in the return
    -- workflow until physical receipt reconciles the assigned stock item.
    (p_expected_status = 'dispatched' and p_next_status in ('with_customer', 'return_due', 'returned')) or
    (p_expected_status = 'with_customer' and p_next_status in ('return_due', 'returned')) or
    (p_expected_status = 'return_due' and p_next_status = 'returned') or
    (p_expected_status = 'returned' and p_next_status = 'closed')
  ) then raise exception 'invalid Pocket WiFi fulfilment transition'; end if;

  -- Crossing a physical custody boundary must always create its matching
  -- inventory movement in this transaction. A legacy/imported row may have a
  -- timestamp populated before its status was advanced; silently treating
  -- that timestamp as proof of an earlier stock movement would let the RPC
  -- mark the router dispatched or returned without reconciling inventory.
  -- Same-status saves remain harmless operational edits and do not create a
  -- second movement.
  if p_next_status = 'dispatched' and p_expected_status <> 'dispatched' then
    if v_order.dispatched_at is not null then
      raise exception 'Pocket WiFi dispatch evidence exists before the dispatch transition; reconcile the order first';
    end if;
    if nullif(trim(coalesce(p_courier_tracking, '')), '') is null then raise exception 'courier tracking is required before dispatch'; end if;
    v_item_id := coalesce(p_inventory_item_id, v_order.inventory_item_id);
    if v_item_id is null then raise exception 'a Pocket WiFi inventory item is required before dispatch'; end if;
    -- Quantity alone is not sufficient evidence that a router may leave the
    -- warehouse. An operator can deliberately quarantine a stock record for
    -- damage, cleaning or maintenance while it still has a positive balance.
    -- Enforce its operational availability inside this transaction, rather
    -- than trusting the admin UI's filtered device list.
    select * into v_item from public.inventory_items
    where id = v_item_id
      and product_type = 'pocket_wifi'
      and status = 'available'
    for update;
    if not found then
      if exists (select 1 from public.inventory_items where id = v_item_id and product_type = 'pocket_wifi') then
        raise exception 'selected Pocket WiFi inventory item is not available for dispatch';
      end if;
      raise exception 'Pocket WiFi inventory item not found';
    end if;
    if v_item.quantity_on_hand < 1 then raise exception 'selected Pocket WiFi inventory item is out of stock'; end if;
    update public.inventory_items set quantity_on_hand = quantity_on_hand - 1, updated_at = v_now where id = v_item_id;
    insert into public.inventory_movements (inventory_item_id, movement_type, quantity, reference, notes)
    values (v_item_id, 'dispatch', -1, left(v_order.stripe_session_id, 120), nullif(left(trim(coalesce(p_courier_tracking, '')), 1000), ''));
  elsif p_next_status = 'returned' and p_expected_status <> 'returned' then
    if v_order.returned_at is not null then
      raise exception 'Pocket WiFi return evidence exists before the return transition; reconcile the order first';
    end if;
    if nullif(trim(coalesce(p_return_tracking, '')), '') is null then raise exception 'return tracking is required before receipt'; end if;
    v_return_disposition := lower(trim(coalesce(p_return_disposition, '')));
    if v_return_disposition not in ('restock', 'quarantine', 'damaged') then raise exception 'invalid Pocket WiFi return disposition'; end if;
    -- Receiving a device increases saleable stock. Never infer that the
    -- corresponding dispatch happened merely from an editable status label:
    -- legacy/manual data can carry `dispatched` (or a later status) without a
    -- recorded hand-off. Releasing stock in that state would inflate inventory
    -- and allow an overlapping rental to be sold. Resolve that exception by
    -- auditing the physical hand-off first.
    if v_order.dispatched_at is null then raise exception 'Pocket WiFi order cannot be returned without a recorded dispatch'; end if;
    v_item_id := v_order.inventory_item_id;
    if v_item_id is null then raise exception 'dispatched Pocket WiFi order has no inventory item to return'; end if;
    select * into v_item from public.inventory_items where id = v_item_id and product_type = 'pocket_wifi' for update;
    if not found then raise exception 'assigned Pocket WiFi inventory item not found'; end if;
    -- A non-restocked return must also leave the dispatchable inventory pool.
    -- Keeping its previous `available` status would let a later stock
    -- adjustment accidentally make a quarantined or damaged unit eligible for
    -- dispatch without a deliberate inspection decision.
    if v_return_disposition = 'restock' then
      update public.inventory_items
      set quantity_on_hand = quantity_on_hand + 1,
          status = 'available',
          updated_at = v_now
      where id = v_item_id;
    else
      update public.inventory_items
      set status = case when v_return_disposition = 'damaged' then 'damaged' else 'quarantined' end,
          updated_at = v_now
      where id = v_item_id;
    end if;
    insert into public.inventory_movements (inventory_item_id, movement_type, quantity, reference, notes)
    values (
      v_item_id,
      case v_return_disposition when 'restock' then 'return' when 'damaged' then 'return_damaged' else 'return_quarantined' end,
      case when v_return_disposition = 'restock' then 1 else 0 end,
      left(v_order.stripe_session_id, 120),
      nullif(left(trim(coalesce(p_return_tracking, '')), 1000), '')
    );
  end if;

  update public.orders set
    fulfilment_status = p_next_status,
    courier_tracking = case when p_courier_tracking is null then courier_tracking else nullif(left(trim(p_courier_tracking), 200), '') end,
    return_tracking = case when p_return_tracking is null then return_tracking else nullif(left(trim(p_return_tracking), 200), '') end,
    return_disposition = case when p_next_status = 'returned' and p_expected_status <> 'returned' then v_return_disposition else return_disposition end,
    notes = case when p_notes is null then notes else left(p_notes, 1000) end,
    inventory_item_id = coalesce(v_order.inventory_item_id, case when p_next_status = 'dispatched' then p_inventory_item_id end),
    dispatched_at = case when p_next_status = 'dispatched' and p_expected_status <> 'dispatched' then v_now else dispatched_at end,
    returned_at = case when p_next_status = 'returned' and p_expected_status <> 'returned' then v_now else returned_at end,
    updated_at = v_now
  where id = p_order_id
  returning * into v_order;
  return v_order;
end;
$$;
