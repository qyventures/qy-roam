-- Inventory quantity and its audit record must change atomically. The admin
-- API uses only this function for adjustments, dispatches and returns.
create or replace function public.qy_adjust_inventory(
  p_item_id bigint,
  p_delta integer,
  p_type text,
  p_reference text default null,
  p_notes text default null
)
returns public.inventory_items
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item public.inventory_items%rowtype;
begin
  if p_item_id is null or p_item_id < 1 then raise exception 'invalid inventory item'; end if;
  if p_delta is null or p_delta = 0 then raise exception 'inventory adjustment must not be zero'; end if;
  if coalesce(length(trim(p_type)), 0) = 0 then raise exception 'movement type is required'; end if;

  update public.inventory_items
  set quantity_on_hand = quantity_on_hand + p_delta,
      updated_at = now()
  where id = p_item_id
    and quantity_on_hand + p_delta >= 0
  returning * into v_item;
  if not found then
    if exists (select 1 from public.inventory_items where id = p_item_id) then
      raise exception 'inventory quantity cannot be negative';
    end if;
    raise exception 'inventory item not found';
  end if;

  insert into public.inventory_movements (inventory_item_id, movement_type, quantity, reference, notes)
  values (p_item_id, left(trim(p_type), 40), p_delta, nullif(left(trim(coalesce(p_reference, '')), 120), ''), nullif(left(trim(coalesce(p_notes, '')), 1000), ''));
  return v_item;
end;
$$;
revoke all on function public.qy_adjust_inventory(bigint,integer,text,text,text) from public;
grant execute on function public.qy_adjust_inventory(bigint,integer,text,text,text) to service_role;

