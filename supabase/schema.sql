create or replace function public.qy_reserve_pocket_wifi(
  p_checkout_request_id text,
  p_travel_start date,
  p_travel_end date,
  p_inventory integer,
  p_expires_at timestamptz,
  p_stripe_hold_count integer default 0,
  p_stripe_hold_request_ids text[] default array[]::text[]
)
returns table(reserved boolean, remaining integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.checkout_reservations%rowtype;
  v_booked integer;
  v_reserved integer;
  v_committed integer;
  v_saleable_inventory integer;
  v_effective_inventory integer;
begin
  if p_checkout_request_id is null or p_checkout_request_id !~ '^[A-Za-z0-9_-]{16,80}$' then
    raise exception 'invalid checkout request id';
  end if;
  if p_travel_start is null or p_travel_end is null or p_travel_end < p_travel_start then
    raise exception 'invalid reservation dates';
  end if;

  -- A single transaction-level lock makes capacity calculation plus insertion
  -- atomic across every application instance.
  perform pg_advisory_xact_lock(hashtext('qy_roam_pocket_wifi_checkout'));
  -- Expiry events normally release holds immediately. Retain an unconfirmed
  -- hold through Stripe's webhook retry window so a delayed paid event cannot
  -- appear after the router was sold to another customer.
  delete from public.checkout_reservations where expires_at <= now() - interval '4 days';

  -- The configured fleet limit protects against an accidental over-count in
  -- the stock register, but physical saleable stock is the hard ceiling. A
  -- unit in quarantine, maintenance or with no on-hand balance must never be
  -- promised by checkout simply because the environment still says "10".
  select coalesce(sum(quantity_on_hand), 0)::integer into v_saleable_inventory
  from public.inventory_items
  where product_type = 'pocket_wifi'
    and status = 'available';
  v_effective_inventory := least(greatest(0, p_inventory), v_saleable_inventory);

  select * into v_existing
  from public.checkout_reservations
  where checkout_request_id = p_checkout_request_id;
  if found then
    if v_existing.travel_start <> p_travel_start or v_existing.travel_end <> p_travel_end then
      raise exception 'checkout request id was already used for different dates';
    end if;
  end if;

  select count(*)::integer into v_booked
  from public.orders
  where product_type = 'pocket_wifi'
    and (payment_status = 'paid' or fulfilment_status = 'awaiting_payment')
    and travel_start <= p_travel_end
    and travel_end >= p_travel_start
    -- A recorded dispatch with an assigned stock item already decrements
    -- quantity_on_hand, which is the saleable inventory ceiling above. Do not
    -- count it again here. Legacy dispatched rows without an assigned item
    -- have no evidence of that stock movement, so conservatively retain them
    -- as commitments until reconciled or returned.
    and (dispatched_at is null or inventory_item_id is null)
    and (
      fulfilment_status not in ('cancelled', 'payment_failed', 'returned', 'closed')
      or (fulfilment_status = 'cancelled' and dispatched_at is not null and returned_at is null and inventory_item_id is null)
    );

  -- Stripe holds passed by the app are counted once. Reservations already
  -- represented by those sessions are excluded from the database count.
  select count(*)::integer into v_reserved
  from public.checkout_reservations
  where expires_at > now() - interval '4 days'
    and travel_start <= p_travel_end
    and travel_end >= p_travel_start
    and not (checkout_request_id = any(coalesce(p_stripe_hold_request_ids, array[]::text[])));

  v_committed := v_booked + v_reserved + greatest(0, coalesce(p_stripe_hold_count, 0));

  -- A process can reserve capacity and then fail before it creates or links a
  -- Stripe Session. On retry, the row above already exists, but the physical
  -- fleet may have shrunk in the meantime (for example, an operator
  -- quarantined a router). The existing hold is included in v_reserved unless
  -- Stripe already represents it, so approve it only while all current
  -- commitments still fit inside the current saleable/configured ceiling.
  -- This prevents an old request id from bypassing the same stock boundary a
  -- fresh checkout must pass before exposing a payment URL.
  if v_existing.checkout_request_id is not null then
    return query select v_effective_inventory >= 1 and v_committed <= v_effective_inventory,
      greatest(0, v_effective_inventory - v_committed);
    return;
  end if;

  if v_effective_inventory < 1 or v_committed >= v_effective_inventory then
    return query select false, greatest(0, v_effective_inventory - v_committed);
    return;
  end if;

  insert into public.checkout_reservations (
    checkout_request_id, travel_start, travel_end, expires_at
  ) values (
    p_checkout_request_id, p_travel_start, p_travel_end, p_expires_at
  );
  return query select true, greatest(0, v_effective_inventory - v_committed - 1);
end;
$$;

